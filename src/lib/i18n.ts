export type Locale = keyof typeof dictionaries
export type DictionaryKey = keyof typeof dictionaries.en

export function getTranslation(locale: Locale, key: DictionaryKey): string {
  return dictionaries[locale]?.[key] || dictionaries.en[key] || (key as string)
}

/**
 * Returns team name in requested locale, falling back gracefully to English name if Malayalam name is missing.
 */
export function getTeamName(
  team: any,
  locale: Locale = 'en'
): string {
  const t = Array.isArray(team) ? team[0] : team
  if (!t) return 'TBD'
  if (locale === 'ml' && t.name_ml && t.name_ml.trim().length > 0) {
    return t.name_ml.trim()
  }
  return t.name || 'TBD'
}

/**
 * Returns team short name in requested locale, falling back to English short name if missing.
 */
export function getTeamShortName(
  team: any,
  locale: Locale = 'en'
): string {
  const t = Array.isArray(team) ? team[0] : team
  if (!t) return 'TBD'
  if (locale === 'ml' && t.short_name_ml && t.short_name_ml.trim().length > 0) {
    return t.short_name_ml.trim()
  }
  return t.short_name || 'TBD'
}

/**
 * Checks if a team is missing a Malayalam name or short name (used to flag to admins).
 */
export function isMissingMalayalamName(
  team: any
): boolean {
  const t = Array.isArray(team) ? team[0] : team
  if (!t) return false
  return !t.name_ml || t.name_ml.trim() === '' || !t.short_name_ml || t.short_name_ml.trim() === ''
}
